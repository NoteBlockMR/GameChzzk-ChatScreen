package.path='obs-plugin/?.lua;'..package.path
local ffi=require('ffi');local bit=require('bit')
local overlay=require('chzzk_overlay').new()
assert(overlay:adopt({},'CHZZK Overlay Native Test',360,500))
local user=ffi.load('user32');local original=tonumber(user.GetWindowLongPtrW(overlay.hwnd,-20))
assert(overlay:set_locked(true,80))
local locked=tonumber(user.GetWindowLongPtrW(overlay.hwnd,-20))
assert(bit.band(locked,0x20)~=0 and bit.band(locked,0x80000)~=0 and bit.band(locked,0x08000000)~=0)
assert(bit.band(tonumber(user.GetWindowLongPtrW(overlay.hwnd,-16)),0xc40000)==0)
assert(overlay:toggle(90))
assert(bit.band(tonumber(user.GetWindowLongPtrW(overlay.hwnd,-20)),0x20)==0)
overlay:toggle_visible();assert(user.IsWindowVisible(overlay.hwnd)==0)
overlay:show();assert(user.IsWindowVisible(overlay.hwnd)~=0)
local hwnd=overlay.hwnd;overlay:restore()
assert(tonumber(user.GetWindowLongPtrW(hwnd,-20))==overlay.exstyle)
print('OVERLAY_NATIVE_OK: own window, click-through flags, frame, hide/show, restore')
